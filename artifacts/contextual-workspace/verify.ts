mkdirSync(PATHS.files, { recursive: true });
const sql = new DatabaseSync(join(HOME, "perry.sqlite"));
let runtime = new Runtime(sql, schema as never, modules, { storageDir: join(HOME, "storage") });
const key = process.env.DASHBOARD_KEY;
const checks: string[] = [];
const pass = (name: string) => { checks.push(name); console.log(`PASS ${name}`); };
const insert = (table: string, value: Record<string, unknown>) => runtime.store.insert(table, value);
const project = insert("projects", { name: "Creative project", createdAt: Date.now(), updatedAt: Date.now() });
const chat = (title: string, projectId?: string, extra = {}) => insert("conversations", { channel: "web", externalId: crypto.randomUUID(), threadId: crypto.randomUUID(), title, lastMessageAt: Date.now(), ...(projectId ? { projectId } : {}), ...extra });
const a = chat("Creative task", project), b = chat("Other project chat", project), c = chat("Unrelated chat"), fresh = chat("Fresh chat");
const guest = chat("Guest", undefined, { contactId: insert("contacts", { name: "Test contact" }) });
const file = (name: string, contents = "fixture") => { const path = join(PATHS.files, name); writeFileSync(path, contents); return path; };
const add = async (conversationId: string, path: string, extra = {}) => await runtime.runMutation("library:add", { path, conversationId, how: "added", by: "perry", ...extra }, { internal: true }) as string;
const fileSchema = z.object({ id: z.string(), name: z.string(), status: z.string(), role: z.string(), latest: z.boolean(), pinned: z.boolean(), hidden: z.boolean(), source: z.object({ runId: z.string().optional(), conversationId: z.string() }) });
const pageSchema = z.object({ page: z.array(fileSchema), isDone: z.boolean(), continueCursor: z.string() });
async function files(conversationId: string, extra = {}) {
  return pageSchema.parse((await runtime.runQuery("workspace:files", { key, conversationId, scope: "chat", working: false, hidden: false, paginationOpts: { numItems: 50, cursor: null }, ...extra })).value);
}
const v1path = file("design-v1.md", "First design");
const v1 = await add(a, v1path, { versionLabel: "Draft" });
const v2 = await add(a, file("design-v2.md", "Final design"), { versionOf: v1, versionLabel: "Final" });
await add(b, file("b.md"));
const unrelated = await add(c, file("unrelated.md"));
file("neighbour-scratch.md");
assert.equal((await files(fresh)).page.length, 0);
assert.equal((await files(a)).page.length, 2);
assert.equal((await files(a)).page.find((item) => item.id === v1)?.latest, false);
assert.equal((await files(a)).page.find((item) => item.id === v2)?.latest, true);
assert.equal((await files(a, { scope: "project" })).page.length, 3);
assert.equal(fileSchema.parse((await runtime.runQuery("workspace:latest", { key, conversationId: a, scope: "chat" })).value).id, v2);
assert.equal((await runtime.runQuery("workspace:file", { key, conversationId: a, scope: "chat", id: unrelated })).value, null);
await assert.rejects(runtime.runQuery("workspace:files", { key: "wrong", conversationId: a, scope: "chat", working: false, hidden: false, paginationOpts: { numItems: 50, cursor: null } }));
await assert.rejects(files(guest));
