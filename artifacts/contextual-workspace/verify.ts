import assert from "node:assert/strict";
import { mkdirSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";
import schema from "../../convex/schema";
import { modules } from "../../server/modules";
import { Runtime } from "../../server/runtime";
import { HOME, PATHS } from "../../runner/home";
import { workspaceSafe } from "../../convex/lib/workspace";
import { z } from "zod";

assert(process.env.PERRY_HOME?.includes("workspace-verification"), "Use a throwaway PERRY_HOME containing workspace-verification.");
