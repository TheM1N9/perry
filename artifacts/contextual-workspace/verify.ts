const working = await add(a, file("intermediate.json", "{}"), { role: "working" });
assert(!(await files(a)).page.some((item) => item.id === working));
assert((await files(a, { working: true })).page.some((item) => item.id === working));
await runtime.runMutation("workspace:attach", { key, conversationId: a, id: unrelated });
assert((await files(a)).page.some((item) => item.id === unrelated));
await runtime.runMutation("workspace:setView", { key, conversationId: a, scope: "chat", id: v1, hidden: true, pinned: true });
assert(!(await files(a)).page.some((item) => item.id === v1));
assert((await files(a, { hidden: true })).page.find((item) => item.id === v1)?.pinned);
assert(existsSync(v1path));
assert(runtime.store.get(v1));
pass("registered intermediates, explicit Library attachment and non-destructive pin/hide");
const task = insert("tasks", { title: "Background render", prompt: "Render", origin: a, status: "running", plan: [{ title: "Render image", status: "active" }], createdAt: Date.now(), updatedAt: Date.now() });
const background = chat("Background", project, { taskId: task });
await runtime.store.patch(task, { conversationId: background });
const bg = await add(background, file("background.md"));
assert((await files(a)).page.some((item) => item.id === bg));
assert(!(await files(c)).page.some((item) => item.id === bg));
const workSchema = z.array(z.object({ id: z.string(), status: z.string(), currentStep: z.string().optional(), outputs: z.array(z.object({ id: z.string() })) }));
let work = workSchema.parse((await runtime.runQuery("workspace:work", { key, conversationId: a, scope: "chat", history: false })).value);
assert.equal(work.find((item) => item.id === task)?.currentStep, "Render image");
await runtime.store.patch(task, { status: "blocked", question: "Need approval" });
work = workSchema.parse((await runtime.runQuery("workspace:work", { key, conversationId: a, scope: "chat", history: false })).value);
assert.equal(work.find((item) => item.id === task)?.status, "waiting");
assert(work.find((item) => item.id === task)?.outputs.some((item) => item.id === bg));
await runtime.store.patch(task, { status: "failed", error: "Test render failure" });
work = workSchema.parse((await runtime.runQuery("workspace:work", { key, conversationId: a, scope: "chat", history: false })).value);
assert.equal(work.find((item) => item.id === task)?.status, "failed");
assert(work.find((item) => item.id === task)?.outputs.some((item) => item.id === bg));
pass("background outputs return only to origin and live task state uses the existing lifecycle");
const run = insert("runs", { conversationId: a, prompt: "Create a file", status: "running", startedAt: Date.now() });
const turn = insert("codexTurns", { conversationId: a, runId: run, prompt: "Create", instructions: "", status: "running", createdAt: Date.now() });
const sharedPath = file("shared.md");
await runtime.runMutation("media:shareFromTurn", { turnId: turn, path: sharedPath }, { internal: true });
const shared = (await files(a)).page.find((item) => item.name === "shared.md");
assert.equal(shared?.source.runId, run);
await runtime.runMutation("media:shareFromTurn", { turnId: turn, path: join(PATHS.files, "failed-upload.md") }, { internal: true });
assert(!(await files(a)).page.some((item) => item.name === "failed-upload.md"));
await runtime.runMutation("media:shareFromLibrary", { turnId: turn, id: unrelated }, { internal: true });
assert((await files(a)).page.some((item) => item.id === unrelated));
pass("share_file registers stable artifact/run identity and failed files never become ready");
const missingPath = file("missing.md");
const missing = await add(a, missingPath);
rmSync(missingPath);
await runtime.runMutation("library:dropMissing", { ids: [missing] }, { internal: true });
assert.equal((await files(a)).page.find((item) => item.id === missing)?.status, "unavailable");
writeFileSync(missingPath, "restored");
assert.equal((await files(a)).page.find((item) => item.id === missing)?.status, "ready");
await runtime.runMutation("library:backfill", {}, { internal: true });
await runtime.runMutation("library:backfill", {}, { internal: true });
assert(!(await files(a)).page.some((item) => item.id === working), "Backfill must retain working-file roles");
const ids = (await files(a, { working: true, hidden: true })).page.map((item) => item.id);
assert.equal(new Set(ids).size, ids.length);
assert(!workspaceSafe(join(HOME, "browser", "Cookies"), "Cookies"));
assert(!workspaceSafe(join(PATHS.files, ".env"), ".env"));
assert(!workspaceSafe(join(PATHS.files, "node_modules", "index.js"), "index.js"));
const storageId = await runtime.storeFile(new Blob(["Stored input"], { type: "text/plain" }));
await runtime.runMutation("media:attachStored", { conversationId: a, messageKey: "stored-input", storageId, fileName: "stored-input.txt", contentType: "text/plain", size: 12 }, { internal: true });
rmSync(join(HOME, "storage", storageId));
assert.equal((await files(a)).page.find((item) => item.name === "stored-input.txt")?.status, "unavailable");
pass("missing local/stored bytes recover, repeated registration/backfill deduplicates and secrets stay hidden");
for (let i = 0; i < 65; i++) await add(a, file(`collection-${i}.json`, "{}"));
const first = await files(a);
const second = await files(a, { paginationOpts: { numItems: 50, cursor: first.continueCursor } });
assert(!first.isDone); assert(second.isDone); assert(second.page.length > 0);
assert(!first.page.some((item) => second.page.some((other) => other.id === item.id)));
const imagePath = file("late-image.png");
writeFileSync(imagePath, Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jT3sAAAAASUVORK5CYII=", "base64"));
const lateImage = await add(a, imagePath);
const filtered = await files(a, { kind: "image" });
assert(filtered.isDone && filtered.page.some((item) => item.id === lateImage), "Filters must run before pagination");
pass("bounded indexed pagination and type filters visit a large collection without duplicates");
await runtime.stop();
sql.close();
const reopened = new DatabaseSync(join(HOME, "perry.sqlite"));
runtime = new Runtime(reopened, schema as never, modules, { storageDir: join(HOME, "storage") });
assert((await files(a, { hidden: true })).page.find((item) => item.id === v1)?.pinned);
assert((await files(a)).page.some((item) => item.id === bg));
pass("database/runner restart preserves membership and view metadata");
writeFileSync(resolve("artifacts/contextual-workspace/report.json"), JSON.stringify({ passed: checks, fixture: { home: HOME, chat: a, project, otherChat: c, version: v2 }, createdAt: new Date().toISOString() }, null, 2) + "\n");
await runtime.stop(); reopened.close();
