const patch=(table:string,id:string,fields:Record<string,unknown>)=>{
 const row=p.rows(table).find(x=>x._id===id)!;
 const {_id,...doc}=row;
 for(const [key,value] of Object.entries(fields)){if(value===undefined)delete doc[key];else doc[key]=value;}
 p.sql(`UPDATE doc_${table} SET doc=? WHERE _id=?`,[JSON.stringify(doc),id]);
};
const finishQueued=(chat:string)=>{
 for(const t of p.turnsOf(chat))patch('codexTurns',t._id,{status:'done',finalizedAt:Date.now()});
 patch('conversations',chat,{pendingTurns:0});
};
